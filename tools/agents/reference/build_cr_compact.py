#!/usr/bin/env python3
"""Build CR_COMPACT.txt from MTG_COMP_RULES_20260807.txt (generated; regenerate, never hand-edit).

One rule or glossary entry per line, wrapped lines joined, Example paragraphs dropped, ASCII quotes,
table of contents / intro / credits removed. Full text stays in the source file; use
`python3 tools/agents/lookup.py cr <number>` for a rule with its examples.
"""
import re, sys, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "MTG_COMP_RULES_20260807.txt")
OUT = os.path.join(HERE, "CR_COMPACT.txt")

RULE = re.compile(r"^(\d{3}(?:\.\d+[a-z]?)?)\.?\s+\S")
SECT = re.compile(r"^(\d)\. [A-Z]")


def ascii_(s):
    for a, b in (("“", '"'), ("”", '"'), ("‘", "'"), ("’", "'"), ("—", "--"), ("–", "-"), ("®", ""), ("™", "")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()


def main():
    L = open(SRC, encoding="utf-8").read().splitlines()
    # body starts at the second occurrence of "1. Game Concepts" (first is the contents list)
    idx = [i for i, l in enumerate(L) if l.startswith("1. Game Concepts")]
    start = idx[1] if len(idx) > 1 else idx[0]
    gl = [i for i, l in enumerate(L) if l.strip() == "Glossary"]
    glossary = gl[-1] if gl else len(L)
    cr = [i for i, l in enumerate(L) if l.strip() == "Credits"]
    end = cr[-1] if cr else len(L)

    out, cur, in_ex = [], None, False

    def flush():
        nonlocal cur
        if cur:
            out.append(ascii_(cur))
        cur = None

    for i in range(start, end):
        l = L[i]
        if i == glossary:
            flush()
            out.append("== GLOSSARY ==")
            in_ex = False
            continue
        if not l.strip():
            if i < glossary:
                continue
            flush()  # glossary entries are blank-line separated
            in_ex = False
            continue
        if i < glossary:
            if re.match(r"^\s*Example:", l):
                flush(); in_ex = True; continue
            m = RULE.match(l.strip())
            # a cross-reference wrapped onto a new line ("... See rule\n 704. See also ...") is not a new rule
            if m and cur and re.match(r"\d{3}\.\d", cur) and re.search(r"\b(?:rules?|and|or|through|see)$", cur.strip(), re.I):
                cur += " " + l.strip(); continue
            if m:
                flush(); in_ex = False; cur = l.strip(); continue
            if SECT.match(l) or re.match(r"^\d{3}\. ", l.strip()):
                flush(); in_ex = False; out.append(ascii_(l)); continue
            if in_ex:
                continue
            if l.startswith("   "):
                cur = (cur or "") + " " + l.strip()
            else:
                cur = (cur or "") + " " + l.strip()
        else:
            cur = (cur + " " + l.strip()) if cur else l.strip()
    flush()
    open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(len(out), "lines,", os.path.getsize(OUT) // 4, "tok~")
    heads = [(i, l) for i, l in enumerate(out) if re.match(r"^(\d\. |\d{3}\. )", l) or l.startswith("== GLOSSARY")]
    idx = ["# CR index (generated by build_cr_compact.py): line in CR_COMPACT.txt, approx tokens, heading. Use: python3 tools/agents/lookup.py cr <rule number>"]
    for k, (i, l) in enumerate(heads):
        j = heads[k + 1][0] if k + 1 < len(heads) else len(out)
        idx.append("%d\t%d\t%s" % (i + 1, sum(len(x) for x in out[i:j]) // 4, l[:60]))
    # game rules: chapters 1-7 and 9 without 701/702 (keyword text lives in ai_lab/KEYWORD_CR_FULLTEXT.toon), no glossary, no chapter 8
    keep, on = [], False
    for l in out:
        m = re.match(r"^(\d)\. [A-Z]", l)
        if m:
            on = m.group(1) in "1234567" or m.group(1) == "9"
        if l.startswith("== GLOSSARY"):
            on = False
        if on and (not re.match(r"^70[12]\.", l) or re.match(r"^702\.1[a-z]?\.?\s", l) or re.match(r"^70[12]\.\s", l) or re.match(r"^701\.1\.?\s", l)):
            keep.append(l)
    # drop 701/702 body lines: lines whose rule id starts with 701 or 702
    keep = [l for l in keep if not re.match(r"^70[12]\.\d", l) or re.match(r"^702\.1[a-z]?\.?\s", l) or re.match(r"^701\.1\.?\s", l)]
    hdr = ("# GAME RULES (Comprehensive Rules 2026-08-07, chapters 1-7 and 9; no glossary, no chapter 8 multiplayer, no 701/702 keyword text (except the general rules 701, 701.1, 702 and 702.1a-d), no examples).\n"
           "# !!! REFERENCED ONLY IN ANALYSIS: do not read unless a task needs a rule's exact wording. Use `python3 tools/agents/lookup.py cr <number>` for one rule,\n"
           "# `lookup.py cr index` for sections. Keyword rules: ai_lab/KEYWORD_MERGED.toon, KEYWORD_CR_FULLTEXT.toon. Generated by build_cr_compact.py. ~%dk tokens.\n")
    body = "\n".join(keep) + "\n"
    open(os.path.join(HERE, "CR_GAME_RULES.txt"), "w", encoding="utf-8").write(hdr % (len(body) // 4000) + body)
    print("CR_GAME_RULES.txt", len(body) // 4, "tok~")
    # tag-relevant rules: whole chapters used by tag work, plus the non-keyword rules the tag files cite
    tag_ch = {"106", "111", "121", "122", "602", "603", "608", "613", "614", "615", "704", "724", "903"}
    tag_sub = ("110.2a", "118.8", "201.5", "205.2", "205.3", "205.4", "305.6", "601.2f", "610.3c")
    tkeep = []
    for l in out:
        m = re.match(r"^(\d{3}(?:\.\d+[a-z]?)?)\.?\s", l)
        if not m:
            continue
        rid = m.group(1)
        if rid.split(".")[0] in tag_ch or any(rid.startswith(c) for c in tag_sub):
            tkeep.append(l)
    thdr = ("# TAG-RELEVANT RULES (Comprehensive Rules 2026-08-07): chapters 603, 608, 613, 614, 615, 704, 903, 106, 111, 121, 122, 602, 724, plus cited rules\n"
            "# 110.2a, 118.8, 201.5, 205.2-205.4, 305.6, 601.2f, 610.3c. No examples.\n"
            "# !!! REFERENCED ONLY IN ANALYSIS: not read by any tag script; do not read unless a task needs several of these rules at once.\n"
            "# Single rule: `python3 tools/agents/lookup.py cr <number>`. Keyword rules: ai_lab/KEYWORD_MERGED.toon. Generated by build_cr_compact.py. ~%dk tokens.\n")
    tbody = "\n".join(tkeep) + "\n"
    open(os.path.join(HERE, "CR_TAG_RELEVANT.txt"), "w", encoding="utf-8").write(thdr % (len(tbody) // 4000) + tbody)
    print("CR_TAG_RELEVANT.txt", len(tkeep), "rules", len(tbody) // 4, "tok~")
    open(os.path.join(HERE, "CR_INDEX.txt"), "w", encoding="utf-8").write("\n".join(idx) + "\n")


if __name__ == "__main__":
    main()
