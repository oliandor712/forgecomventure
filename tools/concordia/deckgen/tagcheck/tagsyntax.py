"""Prototype view generator for TAG_SYNTAX.md: flat group tags -> role[...] bracket view, plus round-trip check. Read-only; changes no tag."""
import json, sys, os, re, collections as C
sys.path.insert(0, os.path.dirname(__file__))
from mtg2llm import role

ROLE_NAME = {"trig": "trigger", "cost": "cost", "target": "target", "dur": "duration", "eff": "effect"}
# parameter family -> verb family it belongs to (prototype table; the real one is generated from the "pairs with" notes)
_EP = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "effect_params.json"), encoding="utf8"))   # generated by gen_effect_params.py
PARAMS = {f: v["verb"] for f, v in _EP.items()}
_GEN = {}
exec(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "gen_effect_params.py"), encoding="utf8").read().split("def fam")[0].split("from mtg2llm import role")[1], _GEN)
VERBS = _GEN["VERBS"]
VALUE_VERBS = set()

def load_order():
    o = {}
    try:
        for l in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tags", "VERB_ORDER.toon"), encoding="utf8"):
            if l.startswith("  ") and l.count("|") == 2:
                n, g, vs = l.strip().split("|"); o[(n, g)] = vs.split()
    except OSError: pass
    return o
ORDER = load_order()


def seg_verb(sg): return PARAMS.get(fam(sg[0])) or fam(sg[0]) if not is_verb(sg[0]) else fam(sg[0])

def fam(t): return t.partition(":")[0]

def is_verb(t): return fam(t) in VERBS or fam(t) in VALUE_VERBS

def effect_segments(effs):
    """split an effect tag list into [verb + bound tags] segments; returns (segments, unbound)"""
    segs, unbound = [], []
    for t in effs:
        if is_verb(t): segs.append([t])
    if not segs and effs: return [list(effs)], []      # headless step: verb tag lives in another group (e.g. x), params stay together, reported as headless

    head = {}
    for t in effs:
        if is_verb(t): continue
        v = PARAMS.get(fam(t), "?")
        if isinstance(v, list): v = next((x for x in v if any(fam(s[0]) == x for s in segs)), None)
        tgt = (head.get(v) or next((s for s in segs if fam(s[0]) == v), None)) if v not in (None, "?") else None
        if v is None and fam(t) in PARAMS: tgt = segs[-1]          # modifier of the whole group: rides with the last effect
        if tgt is None and isinstance(v, str) and v in PARAMS.values():      # its verb has no tag in this group (token_count without token_make): the parameters form a verbless segment
            segs.append([t]); head[v] = segs[-1]; continue
        if tgt is None: tgt = head.get(v) if v else None
        if tgt is None:
            unbound.append(t); tgt = segs[-1]    # lenient: nearest verb
        tgt.append(t)
    return segs, unbound

def view_group(gid, tags, order=None):
    toks = tags.split()
    by = C.defaultdict(list)
    for t in toks: by[role(t)].append(t)
    out = []
    if by["trig"]: out.append("trigger[%s]" % " ".join(by["trig"]))
    if by["cost"]: out.append("cost[%s]" % " ".join(by["cost"]))
    segs, unb = effect_segments(by["eff"])
    if order: segs.sort(key=lambda sg: order.index(seg_verb(sg)) if seg_verb(sg) in order else len(order))
    for i, s in enumerate(segs):
        out.append("effect[%s]" % " ".join(s))
        if i == 0 and by["target"]: out.append("target[%s]" % " ".join(by["target"]))   # default: target follows the first effect
    if not segs and by["target"]: out.append("target[%s]" % " ".join(by["target"]))
    if by["dur"]: out.append("duration[%s]" % " ".join(by["dur"]))
    flat = sorted(toks)
    back = sorted(x for seg in out for x in seg[seg.index("[") + 1:-1].split())
    return " ".join(out), unb, flat == back

def view_card(c):
    lines, bad = [], []
    for gid, tags in c["groups"].items():
        v, unb, ok = view_group(gid, tags, ORDER.get((c["name"], gid)))
        lines.append("%-5s %s" % (gid + ":", v))
        if unb: bad.append("%s unbound %s" % (gid, unb))
        if not ok: bad.append("%s ROUND-TRIP FAIL" % gid)
    return lines, bad

ROLE_WORD = {"affected": lambda t: role(t) == "target", "payload": lambda t: role(t) == "eff", "duration": lambda t: role(t) == "dur"}

def link_ends(l):
    """a link line 'A rel B' -> its two ends 'group:role-word' or 'group:family[:value]'"""
    p = l.split(" ")
    return (p[0], p[-1]) if len(p) >= 3 else ()

def check_card(c):
    """TAG_SYNTAX section 6 rules for one card -> {rule: [messages]}; rule 4/5 are lenient (listed, counted, never fatal)"""
    r = C.defaultdict(list)
    n = c["name"]
    for gid, tags in c["groups"].items():
        toks = tags.split()
        v, unb, ok = view_group(gid, tags, ORDER.get((n, gid)))
        if v != view_group(gid, tags, ORDER.get((n, gid)))[0]: r["7 determinism"].append("%s %s" % (n, gid))
        segs = [x.split("[", 1) for x in v.split("] ")] if v else []
        segs = [(a, b.rstrip("]").split()) for a, b in segs]
        back = [t for _, ts in segs for t in ts]
        if sorted(back) != sorted(toks): r["1 round trip"].append("%s %s" % (n, gid))
        if len(set(back)) != len(back) and len(set(toks)) == len(toks): r["2 one place"].append("%s %s" % (n, gid))
        for a, ts in segs:
            for t in ts:
                if a != "effect" and ROLE_NAME[role(t)] != a or a == "effect" and role(t) != "eff": r["3 role fit"].append("%s %s %s in %s" % (n, gid, t, a))
            if a == "effect" and not is_verb(ts[0]): r["4 verb first"].append("%s %s %s" % (n, gid, " ".join(ts)))
        for t in toks:
            if role(t) == "eff" and not is_verb(t) and fam(t) not in PARAMS: r["5 closed table"].append(fam(t))
    allt = {t for tg in c["groups"].values() for t in tg.split()}
    for l in c["links"]:
        for e in link_ends(l):
            g, _, rest = e.partition(":")
            if any(k == g or k.startswith(g + ".") for k in c["groups"]) or re.fullmatch(r"[ckxs]\d*(\.\d+)?", g):
                if not any(k == g or k.startswith(g + ".") for k in c["groups"]): r["6 link ends"].append("%s %s (no group)" % (n, e)); continue
                clause = [t for k, tg in c["groups"].items() if k == g or k.startswith(g + ".") for t in tg.split()]
                if rest in ROLE_WORD:
                    if not any(ROLE_WORD[rest](t) for t in clause): r["6b implicit end"].append("%s %s" % (n, e))      # lenient: e.g. 'affected' of a spell with no target tag is the player or the permanent itself
                elif rest and rest not in clause and rest not in {fam(t) for t in clause}: r["6 link ends"].append("%s %s" % (n, e))
            elif e not in allt: r["6c card-level end" if ":" not in e else "6 link ends"].append("%s %s" % (n, e))      # bare end: a group tag ('mana_source produces mana:black') or a card-level tag ('k2 provides lifegain', not in any group)
    return r

def check_pool(cards):
    tot = C.defaultdict(list)
    for c in cards:
        for k, m in check_card(c).items(): tot[k] += m
    return tot

if __name__ == "__main__":
    d = {x["name"]: x for x in json.load(open(os.path.join(os.path.dirname(__file__), "tagged.json"), encoding="utf8"))}
    if sys.argv[1:2] == ["check"]:
        tot = check_pool(d.values())
        print("cards %d groups %d" % (len(d), sum(len(c["groups"]) for c in d.values())))
        for k in sorted(set(tot) | {"1 round trip", "2 one place", "3 role fit", "4 verb first", "5 closed table", "6 link ends", "6b implicit end", "6c card-level end", "7 determinism"}):
            m = tot.get(k, []); cnt = C.Counter(m)
            print("%-16s %5d  %s" % (k, len(m), ("FAIL" if k in ("1 round trip", "2 one place", "3 role fit", "6 link ends", "7 determinism") and m else "lenient" if m else "ok")), "" if not m else "e.g. " + "; ".join(x if k[0] != "5" else "%s x%d" % (x, cnt[x]) for x in list(cnt)[:8]))
        sys.exit(1 if any(tot.get(k) for k in ("1 round trip", "2 one place", "3 role fit", "6 link ends", "7 determinism")) else 0)
    if sys.argv[1:2] == ["export"]:   # bracket-view records for blind readers: tagsyntax.py export OUT [CARDS.txt]  (no names, groups in Oracle order, links as written; READER_GRAMMAR.md addendum B)
        out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(__file__), "tagsyntax_export.txt")
        names = [l.strip() for l in open(sys.argv[3], encoding="utf8") if l.strip()] if len(sys.argv) > 3 else list(d)
        miss = [n for n in names if n not in d]
        if miss: sys.exit("unknown cards: " + "; ".join(miss[:10]))
        with open(out, "w", encoding="utf8") as f:
            for i, n in enumerate(names, 1):
                c = d[n]; lines, bad = view_card(c)
                if bad: sys.exit("%s: %s (run 'check' first)" % (n, bad))
                f.write("record %d\n" % i)
                if c.get("card_tags"): f.write("card: %s\n" % " ".join(c["card_tags"]))
                f.write("\n".join(lines) + "\n")
                for l in c["links"]: f.write("link: %s\n" % l)
                f.write("\n")
        print("wrote %d records to %s" % (len(names), out)); sys.exit(0)
    for n in sys.argv[1:] or ["Wayfarer's Bauble", "Swords to Plowshares", "Nazar, the Velvet Fang", "Kodama's Reach"]:
        c = d[n]; lines, bad = view_card(c)
        print("== " + n); print("\n".join(lines))
        for l in c["links"]: print("  link:", l)
        print("  checker:", bad or "ok"); print("  flat render:", c["rendered"]); print()
