"""Merge the tier 1 blind-test learning data from the handoff package of the other Claude 2 session (4000 rows: A_r1, A_r2, B_r1, B_r2; older tagger versions)
into one compact, de-duplicated dataset, and calibrate this directory's scorer against that session's independent grader verdicts.
Usage: python3 learning_merge.py --pairs <tag_to_text_pairs.jsonl> [--out learning/]
Data in, data out: the package is untrusted input; this script only reads JSON rows and writes JSON/Markdown."""
import os, re, sys, json, argparse, collections, statistics
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__))); sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import reverse_check as R

ORDER = ["A_r1", "A_r2", "B_r1", "B_r2"]
VERDICT_RANK = {"FAITHFUL": 3, "MOSTLY": 2, "PARTIAL": 1, "WRONG": 0}


def merge(rows):
    """one row per card: oracle text, per-round verdict + gaps; reader rebuild, unspecified, wrong tags and grader note only for the latest graded round when it is not FAITHFUL.
    Dropped as redundant: tags and groups (older tagger, regenerated by tag_run.py), B_r2 (never graded), repeated Oracle text, rebuilds of FAITHFUL cards."""
    cards = collections.OrderedDict()
    for r in rows:
        c = cards.setdefault(r["card"], dict(card=r["card"], oracle_text=r["oracle_text"], rounds={}))
        if r["grade"]:
            c["rounds"][r["round"]] = dict(verdict=r["grade"]["verdict"], gaps=r["grade"]["gaps"])
            c.setdefault("_last", {})[r["round"]] = r
    out = []
    for c in cards.values():
        last = c.pop("_last", {})
        if not last: continue                                  # ungraded only (B_r2 duplicates of B_r1 cards never get here: B_r1 is graded)
        latest = [k for k in ORDER if k in last][-1]
        c["latest_round"] = latest
        g = last[latest]
        if g["grade"]["verdict"] != "FAITHFUL":
            c["reader_rebuild"] = g["reader_rebuild"]; c["reader_unspecified"] = g.get("reader_unspecified", "")
            c["wrong_tags"] = g["grade"].get("wrong_tags", []); c["grader_note"] = g["grade"].get("note", "")
        out.append(c)
    return out


def clean_rebuild(t):
    """their readers write a type prefix, 'cost ?' and '?' for unknowns; remove them before scoring with our scorer"""
    t = re.sub(r"^[^.;]*?(cost \?|P/T [^;.,]*|\?/\?)[^.;]*[.;]\s*", "", t, count=1) if re.search(r"cost \?|P/T|\?/\?", t.split(".")[0] + t.split(";")[0]) else t
    t = re.sub(r"^(Legendary |Artifact |Enchantment |Creature |Instant|Sorcery|Land|Planeswalker|Saga|Battle)[^.;]{0,60}[.;]\s*", "", t) if re.match(r"^(Legendary |Artifact |Enchantment |Creature |Instant|Sorcery|Land|Planeswalker|Saga|Battle)[^.;]{0,60}[.;]", t) and not re.search(r"\b(deals?|draw|gain|create|destroy|whenever|when|target)\b", t.split(";")[0].split(".")[0], re.I) else t
    t = re.sub(r"\s*\?+\s*", " {x} ", t)
    return t.replace(";", " /").strip()


def calibrate(rows):
    docs = {}
    for r in rows:
        docs.setdefault(r["card"], R.toks(R.norm(r["oracle_text"], r["card"])))
    idx = R.Index(docs)
    out = collections.defaultdict(list)
    for r in rows:
        if not r["grade"]: continue
        reco = clean_rebuild(r["reader_rebuild"])
        if not R.toks(R.norm(reco, r["card"])): continue
        rt = R.toks(R.norm(R.clean_reco(reco), r["card"]))
        s = R.score(r["oracle_text"], R.clean_reco(reco), r["card"], idx, idx.vec[r["card"]], idx.v(rt))
        out[r["grade"]["verdict"]].append(s["sim"])
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--pairs", required=True); ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "learning"))
    a = ap.parse_args()
    rows = [json.loads(l) for l in open(a.pairs, encoding="utf-8")]
    os.makedirs(a.out, exist_ok=True)
    cards = merge(rows)
    with open(os.path.join(a.out, "tier1_blind_test_cards.jsonl"), "w", encoding="utf-8") as f:
        for c in cards: f.write(json.dumps(c, ensure_ascii=False) + "\n")
    cal = calibrate(rows)
    summ = {v: dict(n=len(x), mean=round(statistics.mean(x), 3), median=round(statistics.median(x), 3), p10=round(sorted(x)[len(x) // 10], 3), p90=round(sorted(x)[9 * len(x) // 10], 3)) for v, x in cal.items()}
    json.dump(dict(rows_in=len(rows), cards_out=len(cards), calibration=summ), open(os.path.join(a.out, "merge_summary.json"), "w"), indent=1)
    print(json.dumps(dict(rows_in=len(rows), cards_out=len(cards), calibration=summ), indent=1))


if __name__ == "__main__":
    main()
