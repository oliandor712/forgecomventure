#!/usr/bin/env python3
"""Writes CATEGORIES.toon: one row per deck (tiers 1-5 and starters) with colours, archetype (build_queue.archetype) and deck power (deck_tier).
Usage: python3 tools/concordia/deckgen/categorize.py   (read-only on decks)"""
import glob, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "../../.."))
sys.path.insert(0, os.path.join(ROOT, "tools/concordia"))
sys.path.insert(0, os.path.join(ROOT, "tools/concordia/balance_lab"))
import deck_tier as dt
import build_queue as bq
import run_batch as rb

DECKS = os.path.join(ROOT, rb.DECKS, "decks")


def main():
    files = sorted(glob.glob(os.path.join(DECKS, "tier*", "*.dck")) + glob.glob(os.path.join(DECKS, "starter", "*.dck")))
    data = dt.build_cache()
    cfg = json.load(open(dt.CONFIG))
    rows = []
    for f in files:
        rel = os.path.relpath(f, DECKS)
        tier = rel.split(os.sep)[0].replace("tier", "") if rel.startswith("tier") else "S"
        r = dt.rate(f, data, cfg)
        arch = "starter" if tier == "S" else bq.archetype(f)
        rows.append((rel.replace(os.sep, "/"), tier, rb.colors(f) or "?", arch, r["power"]))
    out = ["# Deck categories (generated by deckgen/categorize.py; do not edit by hand). archetype: build_queue.archetype (starters are tagged starter). power: deck_tier average card power.",
           "decks[%d|]{file|tier|colours|archetype|power}:" % len(rows)]
    out += ["  %s|%s|%s|%s|%.1f" % r for r in rows]
    open(os.path.join(HERE, "CATEGORIES.toon"), "w").write("\n".join(out) + "\n")
    groups = {}
    for _, t, _, a, _ in rows:
        groups[(t, a)] = groups.get((t, a), 0) + 1
    print("%d decks written" % len(rows))
    for k in sorted(groups):
        print("tier %s %-9s %d" % (k[0], k[1], groups[k]))


if __name__ == "__main__":
    main()
