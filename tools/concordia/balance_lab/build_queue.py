#!/usr/bin/env python3
"""Writes QUEUE.toon: one row per deck (tier 1-5 and starters) with games so far, the 40-game target (H28), colour and archetype.
Usage: python3 tools/concordia/balance_lab/build_queue.py. Read-only on decks; reads records.csv and the card scripts."""
import glob, os, re, sys, collections
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
LAB = os.path.join(ROOT, "tools/concordia/balance_lab")
sys.path.insert(0, LAB)
import run_batch as rb  # counts() uses the same new-deck rules as the batches
TARGET = 40  # starters
AI_TARGET = 25  # AI decks (user, 2026-10-21)
def target(name): return TARGET if "starter" in name else AI_TARGET
CARDS = os.path.join(ROOT, "forge-gui/res/cardsfolder")
MANA = re.compile(r"^(\d+|X|[WUBRGC]|[WUBRG]/[WUBRG]|\{[^}]*\})$")


def card_file(name):
    f = os.path.join(CARDS, name[0].lower(), re.sub(r"[^a-z0-9_]", "", name.lower().replace(" ", "_").replace("-", "_")) + ".txt")
    return open(f).read() if os.path.exists(f) else ""


def cmc(mana):
    total = 0
    for sym in mana.split():
        if sym == "X": continue
        total += int(sym) if sym.isdigit() else 1
    return total


def archetype(deck):
    """Tier 1 uses archetype_rules (tokens, tribal with a commander clause, aggro; interaction is a tag, not an archetype).
    Tiers 2-5 keep the simple tag rule from the Main list (quantities counted), scripts from cardsfolder. Order: tokens, ramp, control, aggro, midrange."""
    if re.search(r"tier1", deck.replace(os.sep, "/")):
        sys.path.insert(0, os.path.join(ROOT, "tools/concordia"))
        import archetype_rules as ar
        return ar.classify(deck, 1)["archetype"]
    main = []
    sec = None
    for ln in open(deck):
        ln = ln.strip()
        if ln.startswith("["): sec = ln; continue
        m = re.match(r"(\d+) ([^|]+)", ln)
        if m and sec == "[Main]": main.append((int(m.group(1)), m.group(2).strip()))
    tokens = ramp = removal = creatures = lands = 0
    cmcs = []
    for qty, name in main:
        t = card_file(name)
        if "Types:Land" in t:
            lands += qty; continue
        if re.search(r"^Types:.*Creature", t, re.M): creatures += qty
        if re.search(r"^A:(SP|AB)\$ Token|^SVar:TrigToken", t, re.M) or "TokenScript$" in t: tokens += qty
        if re.search(r"^A:AB\$ Mana|^A:AB\$.*Produced\$", t, re.M): ramp += qty
        if re.search(r"\$ (Destroy|DestroyAll|Exile|DealDamage|DamageAll|Bounce|Counter|Fight|Sacrifice)\b", t): removal += qty
        mc = re.search(r"^ManaCost:(.*)$", t, re.M)
        if mc: cmcs += [cmc(mc.group(1))] * qty
    avg = sum(cmcs) / len(cmcs) if cmcs else 0
    if tokens >= 12: return "tokens"
    if ramp >= 10: return "ramp"
    if removal >= 10 and creatures <= 24: return "control"
    if avg and avg <= 2.8 and creatures >= 24: return "aggro"
    return "midrange"


def main():
    decks = sorted(glob.glob(os.path.join(ROOT, rb.DECKS, "decks", "tier*", "*.dck")) + glob.glob(os.path.join(ROOT, rb.DECKS, "decks", "starter", "*.dck")))
    done = rb.counts(rb.load())
    out = ["# Balance lab queue: games per deck against the target of %d for starters and 25 for AI decks (generated by build_queue.py; do not edit by hand)." % TARGET,
           "queue[%d|]{deck|games_done|target|color|tier|archetype}:" % len(decks)]
    for d in decks:
        name = rb.rel(d)
        col = rb.colors(d) or "?"
        tier = re.search(r"tier(\d)", d).group(1) if "/tier" in d else "S"
        out.append("  %s|%d|%d|%s|%s|%s" % (name, done.get(name, 0), target(name), col, tier, archetype(d) if tier != "S" else "starter"))
    open(os.path.join(LAB, "QUEUE.toon"), "w").write("\n".join(out) + "\n")
    stat = collections.Counter(min(done.get(rb.rel(d), 0), target(rb.rel(d))) for d in decks)
    print("decks %d, games_done total slots %d of %d" % (len(decks), sum(min(done.get(rb.rel(d), 0), target(rb.rel(d))) for d in decks), sum(target(rb.rel(d)) for d in decks)))


if __name__ == "__main__":
    main()
