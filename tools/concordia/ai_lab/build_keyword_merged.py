#!/usr/bin/env python3
"""Build KEYWORD_MERGED.toon and KEYWORD_CR_FULLTEXT.toon (generated; regenerate, never hand-edit).

Merges per keyword: user reference summary (KEYWORD_REFERENCE.toon), CR rule number, printed reminder text
(KEYWORD_REMINDER_TEXT.toon), Scryfall fill (KEYWORD_REMINDER_FILL.toon), first release (KEYWORD_FIRST_RELEASE.toon).
Gaps (no reminder in any file) are filled from the first CR subrule and marked reminder_source=cr_subrule_a.
The CR rule text (no examples, from tools/agents/reference/CR_COMPACT.txt) goes to a separate file that is
flagged: do not read unless absolutely needed.
Source files are not modified.
"""
import csv, io, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
CR = os.path.join(ROOT, "tools/agents/reference/CR_COMPACT.txt")


def rows(name):
    out = []
    for l in open(os.path.join(HERE, name), encoding="utf-8"):
        if l.startswith("  ") and not l.startswith("   "):
            try:
                out.append(next(csv.reader(io.StringIO(l.strip()), escapechar="\\")))
            except StopIteration:
                pass
    return out


def q(s):
    s = " ".join(str(s).split())
    return '"%s"' % s.replace('"', '""') if any(c in s for c in ',"') else s


def main():
    ref = {r[0].lower(): r for r in rows("KEYWORD_REFERENCE.toon") if len(r) >= 4 and r[1] in ("keyword", "action", "ability_word")}
    rem = {r[1].lower(): r for r in rows("KEYWORD_REMINDER_TEXT.toon") if len(r) >= 4}
    fill = {r[0].lower(): r for r in rows("KEYWORD_REMINDER_FILL.toon") if len(r) >= 3}
    first = {r[0].lower(): r for r in rows("KEYWORD_FIRST_RELEASE.toon") if len(r) >= 5}

    lines = [l.rstrip("\n") for l in open(CR, encoding="utf-8")]
    cr, order, cur = {}, [], None
    for l in lines:
        m = re.match(r"^(70[12]\.\d+)\. (.+)$", l)
        if m:
            cur = m.group(1)
            cr[cur] = [m.group(2).strip(), []]
            order.append(cur)
            continue
        if cur and re.match(r"^70[12]\.\d+[a-z]", l):
            if l.startswith(cur):
                cr[cur][1].append(l)
                continue
        if re.match(r"^\d{3}\. ", l) or l.startswith("== GLOSSARY"):
            cur = None
    cr = {k: v for k, v in cr.items() if len(v[0]) < 60}  # drops the two intro paragraphs
    by_name = {v[0].lower(): k for k, v in cr.items()}

    gl = {}
    if "== GLOSSARY ==" in lines:
        for l in lines[lines.index("== GLOSSARY ==") + 1:]:
            gl.setdefault(l.split(" ", 1)[0].lower(), []).append(l)

    def glossary(n):
        for l in gl.get(n.split()[0].lower(), []):
            if l.lower().startswith(n.lower() + " "):
                return l[len(n) + 1:]
        return ""

    names = list(dict.fromkeys([v[0] for v in cr.values()] + [r[0] for r in ref.values()]))
    merged = ["name,kind,cr_rule,example,summary,reminder,reminder_source,first_release,cards_with"]
    full = []
    gaps = 0
    for n in names:
        k = n.lower()
        r, m, f, fr = ref.get(k), rem.get(k), fill.get(k), first.get(k)
        rule = by_name.get(k, "")
        kind = r[1] if r else ("action" if rule.startswith("701") else "keyword")
        example = r[2] if r else (m[4] if m and len(m) > 4 else "")
        summary = r[3] if r else ""
        if m and m[3]:
            rt, src = m[3], "printed"
        elif f and f[2] and f[1] != "none_printed" and f[2]:
            rt, src = f[2], f[1]
        elif rule and cr[rule][1]:
            sub = re.sub(r"^\S+\s+", "", cr[rule][1][0])
            rt, src = sub[:300], "cr_subrule_a"
            gaps += 1
        elif glossary(n):
            rt, src = glossary(n)[:300], "cr_glossary"
            gaps += 1
        else:
            rt, src = "", ("no_cr_rule_ability_word" if kind == "ability_word" else "no_cr_rule")
        merged.append(",".join(q(x) for x in (n, kind, rule, example, summary, rt, src, fr[2] if fr else "", fr[4] if fr else "")))
        if rule:
            full.append("%s,%s,%s" % (rule, q(n), q(" | ".join(cr[rule][1]) or cr[rule][0])))

    hdr = ("# Keyword merge (generated by ai_lab/build_keyword_merged.py; sources unchanged). One row per keyword: user reference summary, CR rule number,\n"
           "# reminder text (printed, else Scryfall fill, else first CR subrule; see reminder_source), first release. Read this file or `python3 tools/agents/lookup.py kw <name>`.\n"
           "# Full CR rule text is NOT here: it is in KEYWORD_CR_FULLTEXT.toon, which is not to be read unless absolutely needed.\n")
    open(os.path.join(HERE, "KEYWORD_MERGED.toon"), "w", encoding="utf-8").write(
        hdr + "keywords[%d]{%s}:\n" % (len(merged) - 1, merged[0]) + "\n".join("  " + x for x in merged[1:]) + "\n")
    fhdr = ("# !!! NOT READ UNLESS ABSOLUTELY NEEDED !!!  (about %dk tokens)\n"
            "# Full Comprehensive Rules text (effective 2026-08-07, rules 701 and 702, examples removed), one row per keyword. Use `python3 tools/agents/lookup.py kw <name> --full`\n"
            "# or `lookup.py cr <number>` to pull a single row. Do not Read this file whole. Generated by ai_lab/build_keyword_merged.py.\n")
    body = "\n".join("  " + x for x in full) + "\n"
    open(os.path.join(HERE, "KEYWORD_CR_FULLTEXT.toon"), "w", encoding="utf-8").write(
        fhdr % (len(body) // 4000) + "rules[%d]{cr_rule,name,text}:\n" % len(full) + body)
    print(len(names), "keywords;", gaps, "gaps filled from CR;", len(full), "full-text rows")


if __name__ == "__main__":
    main()
