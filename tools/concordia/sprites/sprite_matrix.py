#!/usr/bin/env python3
"""Builds the Forge sprite matrix for assigning sprites to Concordia NPCs.

Every enemy/hero sprite atlas under forge-gui/res/adventure/common/sprites is listed with its folder category, its
animations and frame size, and the tags of every enemy (in any plane's world/enemies.json) that uses it: creature
types and other questTags, colors, biome and identity tags, difficulty, boss. Writes sprite_matrix.csv and
sprite_matrix.md next to this script. Run: python3 tools/concordia/sprites/sprite_matrix.py
"""
import collections, csv, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ADV = os.path.abspath(os.path.join(HERE, '..', '..', '..', 'forge-gui', 'res', 'adventure'))
SPRITES = os.path.join(ADV, 'common', 'sprites')

def atlas_info(path):
    anims, size = collections.Counter(), ''
    lines = open(path, errors='replace').read().splitlines()
    for i, l in enumerate(lines):
        if l and not l.startswith(' ') and ':' not in l and not l.endswith('.png'):
            anims[l.strip()] += 1
            if not size:
                for k in lines[i + 1:i + 4]:
                    m = re.match(r'\s*size:\s*(\d+),\s*(\d+)', k)
                    if m: size = '%sx%s' % m.groups(); break
    return anims, size

users = collections.defaultdict(list)
for f in glob.glob(os.path.join(ADV, '*', 'world', 'enemies.json')):
    plane = f.split(os.sep)[-3]
    try:
        data = json.load(open(f))
    except Exception:
        continue
    for e in data:
        sp = (e.get('sprite') or '').replace('\\', '/')
        if sp:
            users[sp.lower()].append((plane, e))

rows = []
for path in sorted(glob.glob(os.path.join(SPRITES, '**', '*.atlas'), recursive=True)):
    rel = os.path.relpath(path, os.path.join(ADV, 'common')).replace(os.sep, '/')
    parts = rel.split('/')
    if parts[1] not in ('enemy', 'heroes'):
        continue
    kind = parts[1]
    cat = parts[2] if kind == 'enemy' and len(parts) > 3 else ('hero' if kind == 'heroes' else '')
    sub = '/'.join(parts[3:-1]) if kind == 'enemy' else ''
    anims, size = atlas_info(path)
    used = users.get(rel.lower(), [])
    names = sorted({e['name'] for _, e in used})
    planes = sorted({p for p, _ in used})
    colors = ''.join(c for c in 'WUBRGC' if any(c in (e.get('colors') or '') for _, e in used))
    ccount = collections.Counter(c for _, e in {e['name']: (p, e) for p, e in used}.values() for c in (e.get('colors') or '') if c in 'WUBRGC')
    primary = ''.join(c for c, n in ccount.items() if n == max(ccount.values())) if ccount else ''
    primary = ''.join(c for c in 'WUBRGC' if c in primary)
    tags = collections.Counter(t for _, e in used for t in (e.get('questTags') or []) if t)
    biome = sorted({t[5:] for t in tags if t.startswith('Biome')})
    ident = sorted({t[8:] for t in tags if t.startswith('Identity')})
    other = [t for t, _ in tags.most_common() if not t.startswith(('Biome', 'Identity'))]
    diffs = sorted({e.get('difficulty') for _, e in used if e.get('difficulty') is not None})
    rows.append({
        'sprite': rel, 'kind': kind, 'category': cat, 'subcategory': sub, 'name': os.path.basename(path)[:-6],
        'frame': size, 'animations': ' '.join(sorted(anims)),
        'has_attack': 'Attack' in anims, 'has_death': 'Death' in anims,
        'role': 'person' if cat in ('humanoid', 'hero') else 'creature',
        'enemies': '; '.join(names), 'planes': ' '.join(planes), 'colors': colors, 'primary_color': primary,
        'color_counts': ' '.join('%s%d' % (c, ccount[c]) for c in 'WUBRGC' if ccount[c]),
        'biomes': ' '.join(biome), 'identity': ' '.join(ident), 'tags': ' '.join(other),
        'difficulty': '-'.join(str(d) for d in (diffs[:1] + diffs[-1:] if len(diffs) > 1 else diffs)),
        'boss': any(e.get('boss') for _, e in used),
        'used_by_concordia': any(p == 'Concordia' for p in planes),
    })

with open(os.path.join(HERE, 'sprite_matrix.csv'), 'w', newline='') as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader(); w.writerows(rows)

# summary
md = ['# Forge sprite matrix', '',
      'Generated by `sprite_matrix.py` from `common/sprites` and every plane\'s `world/enemies.json`. The full table, one',
      'row per sprite, is `sprite_matrix.csv`. Tags come from the enemies that use each sprite, so a sprite no enemy',
      'uses has only its folder category.', '']
cats = collections.Counter(r['category'] for r in rows)
md += ['## By category', '', '| Category | Sprites | Used by an enemy | Colors seen | Most common tags |', '|---|---|---|---|---|']
for cat, n in sorted(cats.items(), key=lambda kv: -kv[1]):
    rs = [r for r in rows if r['category'] == cat]
    used = sum(1 for r in rs if r['enemies'])
    col = collections.Counter(c for r in rs for c in r['colors'])
    tg = collections.Counter(t for r in rs for t in r['tags'].split())
    md.append('| %s | %d | %d | %s | %s |' % (cat, n, used, ' '.join('%s %d' % kv for kv in sorted(col.items(), key=lambda kv: 'WUBRGC'.index(kv[0]))),
                                             ', '.join(t for t, _ in tg.most_common(6))))
md += ['', '## By primary color', '',
       'The primary color is the most common color among the enemies that use a sprite (ties keep both). Many sprites',
       'are reused across planes in several colors, so `colors` in the CSV lists every color seen and `color_counts`',
       'how often.', '', '| Color | Sprites (primary) | People | Creatures |', '|---|---|---|---|']
for c, nm in zip('WUBRGC', ['White', 'Blue', 'Black', 'Red', 'Green', 'Colorless']):
    rs = [r for r in rows if c in r['primary_color']]
    md.append('| %s | %d | %d | %d |' % (nm, len(rs), sum(1 for r in rs if r['role'] == 'person'), sum(1 for r in rs if r['role'] == 'creature')))
md += ['', '## By biome tag', '', '| Biome | Sprites |', '|---|---|']
bi = collections.Counter(b for r in rows for b in r['biomes'].split())
for b, n in bi.most_common():
    md.append('| %s | %d |' % (b, n))
humanoid = collections.Counter(r['subcategory'].split('/')[0] or '(top level)' for r in rows if r['category'] == 'humanoid')
md += ['', '## Humanoid sprites by people', '', '| Subfolder | Sprites |', '|---|---|'] + ['| %s | %d |' % kv for kv in humanoid.most_common()]
human = collections.Counter(r['subcategory'].split('/')[1] if r['subcategory'].count('/') else '(top level)' for r in rows if r['subcategory'].startswith('human'))
md += ['', '## Human sprites by profession', '', '| Subfolder | Sprites | Examples |', '|---|---|---|']
for k, n in human.most_common():
    ex = [r['name'] for r in rows if r['subcategory'].startswith('human') and (r['subcategory'].split('/')[1] if r['subcategory'].count('/') else '(top level)') == k]
    md.append('| %s | %d | %s |' % (k, n, ', '.join(ex[:10])))
unused = [r for r in rows if not r['enemies']]
md += ['', '## Not used by any enemy (%d)' % len(unused), '', ', '.join(r['sprite'][len('sprites/'):-6] for r in unused), '']
open(os.path.join(HERE, 'sprite_matrix.md'), 'w').write('\n'.join(md) + '\n')
print(len(rows), 'sprites;', sum(1 for r in rows if r['enemies']), 'used by enemies')
